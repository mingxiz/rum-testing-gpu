"""Turn validation/results/<tag>/*.json into the paper's LaTeX tables, a
markdown summary, and a comparison with the committed reference results.

    python validation/make_tables.py --tag <tag> [--criterion race] [--reference <dir>]
                                     [--paren speedup|iters|none]

LaTeX table columns (per n): density, m_p, BM-ADMM, CGBFQP-GPU, Flow-ADMM, CGIP,
CGIP-heur. Each entry is the wall time in seconds; with --paren speedup (the
default) it is followed by the speed-up relative to CGIP on the same cell,
t_CGIP / t_solver, in parentheses -- left blank while no CGIP result exists for
the cell. --paren iters prints instead the number of ADMM iterations (BM-ADMM,
Flow-ADMM) or generated columns (the column-generation methods), which is what
the markdown summary always shows. "--" = the solver cannot run the cell
(device memory); CAP = wall cap reached; blank = not run. Bold = fastest among
the solvers that were run.
"""
import argparse
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
from result_store import DENSITY_GRID    # noqa: E402
SOLVERS = [("bm_admm", "BM-ADMM"), ("cgbfqp", "CGBFQP-GPU"), ("flow_admm", "Flow-ADMM"),
           ("cgip", "CGIP"), ("cgip_heur", "CGIP-heur")]
OK_STOPS = ("phi_ub", "ub_target", "ub_rel", "certified", "gap_rel", "below", "converged")


def load_dir(d_path, criterion):
    d = {}
    for p in glob.glob(os.path.join(d_path, "*_%s_*.json" % criterion)):
        r = json.load(open(p))
        d[(r["solver"], r["key"])] = r
    return d


def tag_dir(tag):
    """--tag is a results/<tag> name or a directory (e.g. replication/density_grid/results)."""
    return tag if os.path.isdir(tag) else os.path.join(HERE, "results", tag)


def load(tag, criterion):
    return load_dir(tag_dir(tag), criterion)


def status(r):
    """'ok' | 'cap' | 'infeasible' | 'err' | None (not run)."""
    if r is None:
        return None
    stop = r.get("stop")
    if stop == "infeasible":
        return "infeasible"
    if stop in ("error", "killed") or r.get("wall_s") is None:
        return "err"
    if stop in ("time_limit", "max_iter", "max_iters") or (r.get("converged") is False and stop not in OK_STOPS):
        return "cap"
    return "ok"


def fmt_time(t):
    return ("%.2f" % t) if t < 10 else ("%.1f" % t)


def cell_text(r, paren, t_cgip=None, is_cgip=False):
    st = status(r)
    if st is None:
        return ""
    if st == "infeasible":
        return "--"
    if st == "err":
        return "err"
    if st == "cap":
        return "CAP"
    s = fmt_time(r["wall_s"])
    if paren == "iters" and r.get("iters") is not None:
        s += " (%s)" % format(int(r["iters"]), ",")
    elif paren == "speedup" and t_cgip is not None and not is_cgip:
        s += " (%s)" % fmt_speedup(t_cgip / max(r["wall_s"], 1e-9))
    return s


def fmt_speedup(x):
    if x >= 100:
        return "%d$\\times$" % round(x)
    if x >= 10:
        return "%.0f$\\times$" % x
    return "%.1f$\\times$" % x


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", required=True)
    ap.add_argument("--criterion", default="race")
    ap.add_argument("--reference", default=DENSITY_GRID,
                    help="directory (or results/<tag>) holding the reference results to compare against; default: the committed paper-machine results")
    ap.add_argument("--paren", default="speedup", choices=["speedup", "iters", "none"])
    a = ap.parse_args()
    res = load(a.tag, a.criterion)
    ref_dir = a.reference if os.path.isdir(a.reference) else os.path.join(HERE, "results", a.reference)
    ref = load_dir(ref_dir, a.criterion) if os.path.isdir(ref_dir) else {}
    manifest = json.load(open(os.path.join(ROOT, "data", "manifest.json")))
    os.makedirs(os.path.join(ROOT, "paper", "tables"), exist_ok=True)
    md = ["# Results %s (criterion: %s)\n" % (a.tag, a.criterion),
          "Entries: wall time in seconds (ADMM iterations or generated columns). "
          "`--` = cannot run (device memory); CAP = wall cap. Bold = fastest.\n"]
    paren_txt = {"speedup": "; in parentheses the speed-up relative to CGIP on the same instance "
                            "($t_{\\mathrm{CGIP}}/t$)",
                 "iters": "; in parentheses the number of ADMM iterations (BM-ADMM, Flow-ADMM) or "
                          "generated columns (CGBFQP-GPU, CGIP, CGIP-heur)",
                 "none": ""}[a.paren]
    for n in (18, 19, 20):
        keys = [k for k, r in manifest.items() if r["n"] == n]
        m2 = n * (1 << (n - 1))
        lines = ["%% generated by validation/make_tables.py from %s (--paren %s)" % (os.path.relpath(tag_dir(a.tag), ROOT).replace(os.sep, "/"), a.paren),
                 "\\begin{table}[t]", "\\centering",
                 "\\caption{$n=%d$ ($m_2 = %s$): time to termination criteria in seconds%s; "
                 "Bold = fastest. ``--'' = the solver cannot run the cell (device memory); CAP = wall cap.}"
                 % (n, format(m2, ",").replace(",", "{,}"), paren_txt),
                 "\\label{tab:density%d}" % n,
                 "\\begin{tabular}{lr" + "r" * len(SOLVERS) + "}", "\\toprule",
                 "density & $m_p$ & " + " & ".join(lbl for _, lbl in SOLVERS) + " \\\\", "\\midrule"]
        md.append("\n## n = %d\n\n| density | mp | " % n + " | ".join(l for _, l in SOLVERS) + " |\n|---|---|" + "---|" * len(SOLVERS))
        for k in keys:
            m = manifest[k]
            dens = "pairwise" if m["cat"] == "sparse" else ("%.3f\\%%" % m["density_pct"] if m["density_pct"] < 1 else "%.2f\\%%" % m["density_pct"])
            r_cgip = res.get(("cgip", k))
            t_cgip = r_cgip["wall_s"] if status(r_cgip) == "ok" else None
            times = {s: res[(s, k)]["wall_s"] for s, _ in SOLVERS if status(res.get((s, k))) == "ok"}
            best = min(times, key=times.get) if times else None
            tex_entries, md_entries = [], []
            for s, _ in SOLVERS:
                r = res.get((s, k))
                e = cell_text(r, a.paren, t_cgip, is_cgip=(s == "cgip"))
                tex_entries.append("\\textbf{%s}" % e if (best and s == best) else e)
                e_md = cell_text(r, "iters").replace("$\\times$", "x")
                md_entries.append("**%s**" % e_md if (best and s == best) else e_md)
            lines.append("%s & %s & %s \\\\" % (dens, format(m["mp"], ",").replace(",", "{,}"), " & ".join(tex_entries)))
            md.append("| %s | %s | %s |" % (dens.replace("\\%", "%"), format(m["mp"], ","), " | ".join(md_entries)))
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
        with open(os.path.join(ROOT, "paper", "tables", "tab_n%d_%s.tex" % (n, a.criterion)), "w") as f:
            f.write("\n".join(lines) + "\n")
    # machine line + comparison with the reference machine
    any_r = next(iter(res.values()), {})
    md.append("\nMachine: %s; GPU %s; CPU %s; %s logical cores. Cores busy per run (avg): %s"
              % (any_r.get("hostname"), any_r.get("gpu"), any_r.get("cpu_model"), any_r.get("logical_cores"),
                 ", ".join("%s %.2f" % (s, sum(r["avg_cores"] for (ss, _), r in res.items() if ss == s) /
                                        max(1, sum(1 for (ss, _) in res if ss == s))) for s, _ in SOLVERS
                           if any(ss == s for (ss, _) in res))))
    if ref and a.tag != a.reference:
        md.append("\n## Comparison with the reference machine (%s)\n\n| cell | solver | this run | reference | time ratio | iterations this / ref |\n|---|---|---|---|---|---|"
                  % (next(iter(ref.values())).get("gpu")))
        for (s, k), r in sorted(res.items(), key=lambda kv: (kv[0][1], kv[0][0])):
            q = ref.get((s, k))
            if not q or status(r) != "ok" or status(q) != "ok":
                continue
            md.append("| %s | %s | %s | %s | %.2f | %s / %s |" % (k, s, cell_text(r, "iters"), cell_text(q, "iters"),
                                                                r["wall_s"] / max(q["wall_s"], 1e-9), r.get("iters"), q.get("iters")))
    with open(os.path.join(tag_dir(a.tag), "summary.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    print("wrote paper/tables/tab_n{18,19,20}_%s.tex (--paren %s) and results/%s/summary.md" % (a.criterion, a.paren, a.tag))


if __name__ == "__main__":
    main()
