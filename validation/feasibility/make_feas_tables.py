"""Tables for the feasibility study from validation/results/feasibility/*.json
(+ optional CPU-baseline results dropped into the same folder as
race_cgip_<key>.json / race_cgip_heur_<key>.json).

Writes validation/results/feasibility/FEASIBILITY.md and
paper/tables/tab_feas_pairwise.tex, tab_feas_density.tex. Entries: wall time in
seconds to (UB-OPT)/OPT <= 1%, with the number of columns / iterations; blank
CPU columns until those results exist; "--" = cannot run (memory); CAP = cap.
Also a "time in human units" column for the speed-up message.
"""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
RES = os.path.join(ROOT, "validation", "results", "feasibility")
sys.path.insert(0, os.path.join(ROOT, "validation"))
from result_store import glob_all, FEASIBILITY    # noqa: E402


def human(sec):
    if sec is None:
        return ""
    if sec < 60:
        return "%.2g s" % sec if sec < 10 else "%.0f s" % sec
    if sec < 3600:
        return "%.1f min" % (sec / 60)
    if sec < 86400:
        return "%.1f h" % (sec / 3600)
    return "%.1f days" % (sec / 86400)


def load(prefix):
    """Result files named <criterion>_<solver>_<key>.json (feas_one.py) or
    <solver>_<criterion>_<key>.json (validation/run_one.py, used for the CPU
    baselines); the (solver, key) come from the JSON content, the criterion from
    the content too, so either naming works. CGBFQP results from the stream
    pricing backends (<criterion>_cgbfqp-<pricing>_<key>.json) are used only for
    cells the mask-indexed lattice cannot hold (n >= 33): float32 when it fits
    (bit-identical to the mask kernel), else uint16 block-scaled; the row is
    marked with `backend_note`."""
    d, tagged = {}, {}
    # stores first, the working directory last, so a fresh run overrides the stored record
    for p in glob_all(prefix + "_*.json", first=[RES], folders=FEASIBILITY) + glob_all("*_%s_*.json" % prefix, first=[RES], folders=FEASIBILITY):
        with open(p, encoding="utf-8") as f:
            r = json.load(f)
        if r.get("criterion", prefix) != prefix or r.get("key") is None:
            continue
        k = (r.get("solver") or r.get("method"), r.get("key"))
        if r.get("pricing", "mask") != "mask":
            tagged.setdefault(k, []).append(r)
        else:
            d[k] = r
    for k, rs in tagged.items():
        if k not in d:
            rs.sort(key=lambda r: {"stream_f32": 0, "stream_u16": 1}.get(r.get("pricing"), 9))
            d[k] = dict(rs[0], backend_note=rs[0]["pricing"])
    return d


def ok(r):
    return r is not None and r.get("wall_s") is not None and r.get("stop") not in ("infeasible", "error", "killed") \
        and r.get("converged", True)


def fmt(r, unit):
    if r is None:
        return ""
    if r.get("stop") == "infeasible":
        return "--"
    if not ok(r):
        return "CAP" if r.get("stop") in ("time_limit", "max_iter", "max_iters", "killed") else "err"
    t = r["wall_s"]
    return "%s (%s %s)" % (("%.2f" % t) if t < 10 else ("%.1f" % t), format(int(r["iters"]), ","), unit)


def main():
    race, cert = load("race"), load("cert")
    refs = json.load(open(os.path.join(ROOT, "data", "opt_refs.json")))
    md = ["# Feasibility study\n", "Race criterion (UB-OPT)/OPT <= 1%; OPT certified to (UB-LB)/LB <= 1e-3 (data/opt_refs.json). "
          "Times in seconds; in parentheses columns (CG methods) or ADMM iterations. One process per run, GPU idle before each.\n"]
    os.makedirs(os.path.join(ROOT, "paper", "tables"), exist_ok=True)

    # (1) pairwise, growing n
    keys = sorted({k for (_, k) in race if k.endswith("_sparse")} | {k for (_, k) in cert if k.endswith("_sparse")},
                  key=lambda k: int(k.split("_")[0][1:]))
    md.append("\n## (1) Pairwise design, growing n\n\n| n | mp | 2^n | OPT | OPT certified by (cols, s) | CGBFQP-GPU race | CGIP | CGIP-heur | CGBFQP-GPU in human units | device memory |\n|---|---|---|---|---|---|---|---|---|---|")
    tex = ["% generated by validation/feasibility/make_feas_tables.py", "\\begin{table}[t]", "\\centering",
           "\\caption{Feasibility in the number of alternatives on the pairwise design ($m_p = n(n-1)$): time to termination criteria in seconds (columns generated); ``--'' = cannot run (memory).}",
           "\\label{tab:feas_pairwise}", "\\begin{tabular}{rrrrrr}", "\\toprule",
           "$n$ & $m_p$ & OPT & CGBFQP-GPU & CGIP & CGIP-heur \\\\", "\\midrule"]
    for k in keys:
        n = int(k.split("_")[0][1:]); ref = refs.get(k, {}); c = cert.get(("cgbfqp", k)); r = race.get(("cgbfqp", k))
        gi, gh = race.get(("cgip", k)), race.get(("cgip_heur", k))
        md.append("| %d | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            n, format(n * (n - 1), ","), "2^%d = %s" % (n, format(1 << n, ",")),
            "%.6f" % ref["opt"] if ref else "", ("%s (%s, %.0f s)" % (ref.get("method"), ref.get("n_cols"), ref.get("wall_s"))) if ref else "",
            fmt(r, "cols") + ((" [%s]" % r["backend_note"]) if r and r.get("backend_note") else ""),
            fmt(gi, "cols"), fmt(gh, "cols"), human(r["wall_s"]) if ok(r) else "",
            ("%.1f GB" % (r["device_bytes"] / 2 ** 30)) if r and r.get("device_bytes") else ""))
        note = {"stream_f32": "$^{\\dagger}$", "stream_u16": "$^{\\ddagger}$"}.get((r or {}).get("backend_note"), "")
        if note and "dagger" not in tex[-1]:
            tex.append("\\midrule")          # separates the mask-kernel rows (n <= 32) from the stream-backend rows
        tex.append("%d & %s & %s & %s%s & %s & %s \\\\" % (n, format(n * (n - 1), ",").replace(",", "{,}"),
                   "%.4f" % ref["opt"] if ref else "", fmt(r, "cols"), note, fmt(gi, "cols"), fmt(gh, "cols")))
    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    if any((race.get(("cgbfqp", k)) or {}).get("backend_note") for k in keys):
        tex.append("\\smallskip\\par\\footnotesize $^{\\dagger}$ two-layer float32 pricing backend, $^{\\ddagger}$ two-layer "
                   "uint16 block-scaled backend (Table~\\ref{tab:feas_pricing}); the mask-indexed lattice does not fit for $n \\ge 33$.")
    with open(os.path.join(ROOT, "paper", "tables", "tab_feas_pairwise.tex"), "w", encoding="utf-8") as f:
        f.write("\n".join(tex) + "\n")

    # (2) n = 20, growing density
    dkeys = ["n20_d1pct", "n20_m1380", "n20_m2759", "n20_m6899", "n20_m13797", "n20_dense"]
    md.append("\n## (2) n = 20, growing density\n\n| density | mp | OPT | OPT certified by (its, s) | BM-ADMM race | CGIP | CGIP-heur | BM-ADMM in human units | device memory |\n|---|---|---|---|---|---|---|---|---|")
    tex = ["% generated by validation/feasibility/make_feas_tables.py", "\\begin{table}[t]", "\\centering",
           "\\caption{Feasibility in observation density at $n=20$ ($m_2 = 10{,}485{,}760$): time to termination criteria in seconds (ADMM iterations / columns); ``--'' = cannot run.}",
           "\\label{tab:feas_density}", "\\begin{tabular}{lrrrrr}", "\\toprule",
           "density & $m_p$ & OPT & BM-ADMM & CGIP & CGIP-heur \\\\", "\\midrule"]
    for k in dkeys:
        ref = refs.get(k, {}); r = race.get(("bm_admm", k)); gi, gh = race.get(("cgip", k)), race.get(("cgip_heur", k))
        mp = ref.get("mp") or (r or {}).get("mp")
        dens = (100.0 * mp / (20 * (1 << 19))) if mp else float("nan")
        md.append("| %.1f%% | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            dens, format(mp, ",") if mp else "", "%.6f" % ref["opt"] if ref else "",
            ("%s (%s, %.0f s)" % (ref.get("method"), ref.get("iters") or ref.get("n_cols") or "-", ref.get("wall_s"))) if ref else "",
            fmt(r, "it"), fmt(gi, "cols"), fmt(gh, "cols"), human(r["wall_s"]) if ok(r) else "",
            ("%.1f GB" % r["gpu_pool_peak_gb"]) if r and r.get("gpu_pool_peak_gb") else ""))
        tex.append("%s & %s & %s & %s & %s & %s \\\\" % ("%.0f\\%%" % dens if dens >= 5 else "%.1f\\%%" % dens,
                   format(mp, ",").replace(",", "{,}") if mp else "", "%.4f" % ref["opt"] if ref else "",
                   fmt(r, "it"), fmt(gi, "cols"), fmt(gh, "cols")))
    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    open(os.path.join(ROOT, "paper", "tables", "tab_feas_density.tex"), "w").write("\n".join(tex) + "\n")

    # trajectories summary
    md.append("\n## Trajectories\n\nEvery race JSON carries `trace`: per column (CGBFQP) or per 50-iteration check (BM-ADMM): [step, wall_s, UB, LB]. First/last entries:\n")
    for (s, k), r in sorted(race.items()):
        tr = r.get("trace") or []
        if tr:
            md.append("- %s %s: %d entries; first %s; last %s" % (k, s, len(tr), [round(x, 4) if isinstance(x, float) else x for x in tr[0]],
                                                                 [round(x, 4) if isinstance(x, float) else x for x in tr[-1]]))
    md.append("\nDevice memory: for CGBFQP-GPU the lattice footprint of the layout (`device_bytes`); "
              "for BM-ADMM the pool high-water mark.")
    open(os.path.join(RES, "FEASIBILITY.md"), "w").write("\n".join(md) + "\n")
    print("wrote", os.path.join(RES, "FEASIBILITY.md"), "and paper/tables/tab_feas_{pairwise,density}.tex")


if __name__ == "__main__":
    main()
