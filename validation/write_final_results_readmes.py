def fl(r, k):
    return float(r[k])


def tol(x):
    return {"0.0005": "5e-4", "0.0001": "1e-4", "1e-05": "1e-5", "0.005": "5e-3"}.get(x, x)


def secs(x):
    x = float(x)
    if x >= 3600:
        return "%.2f h" % (x / 3600)
    if x >= 100:
        return "%.0f s (%.1f min)" % (x, x / 60)
    return "%.1f s" % x


def pv(r):
    lo, hi = fl(r, "pval_lo"), fl(r, "pval_hi")
    if abs(lo - hi) < 1e-12:
        return "0" if hi == 0 else "%.4f" % hi
    return "[%.4f, %.4f]" % (lo, hi)


def ci(r):
    return "[%.4f, &infin;)" % fl(r, "ci_lower") if r["ci_lower"] else "not computed"


def record(r):
    return json.load(open(os.path.join(ROOT, r["record"])))


def screened(r):
    return record(r)["results"]["p_value"]["0.05"]["n_screened"]


