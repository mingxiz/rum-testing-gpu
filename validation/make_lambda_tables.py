"""The 15 lambda-study tables for the paper, from the stored records.

    paper/tables/tab_fes_pairwise_l{0,05,1}.tex   n = 25, 27, 30, 32, 35 | m_p | CGBFQP-GPU | CGIP | CGIP-heur
    paper/tables/tab_fes_density_l{0,05,1}.tex    0.1, 0.5, 1, 5 %       | m_p | BM-ADMM    | CGIP | CGIP-heur
    paper/tables/tab_race_n{18,19,20}_l{0,05,1}.tex  the grid cells      | m_p | BM-ADMM | CGBFQP-GPU | Flow-ADMM | CGIP | CGIP-heur

Entries: wall time in seconds to the stopping rule UB <= max(1.01 OPT, 1e-3); the feasibility
tables add the count in parentheses (columns generated, or ADMM iterations); the race tables
show time only, bold = fastest of the three GPU solvers. CGIP columns are left blank (run on
the cluster). "--" = cannot run (device memory); CAP = wall cap. Records are found through
validation/result_store (working directory first, then the replication stores). "--" covers both
a solver that refuses the cell up front (device memory) and one whose run failed. Also writes
validation/results/lambda_study/LAMBDA_STUDY.md with every number including the counts.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "data"))
from result_store import find          # noqa: E402
from gen_instances import CELLS        # noqa: E402

OUT = os.path.join(ROOT, "validation", "results", "lambda_study")
TABLES = os.path.join(ROOT, "paper", "tables")
REFS = json.load(open(os.path.join(ROOT, "data", "opt_refs.json")))
LAMS = [(0, "l0", "0"), (5, "l05", "0.5"), (10, "l1", "1")]
PAIRWISE_N = [25, 27, 30, 32, 35]
# the density set released in final_data/Numerical3 (n = 20): 0.1, 0.5, 1, 5 %
DENSITY = [("m28", r"0.1\%"), ("m138", r"0.5\%"), ("d1pct", r"1\%"), ("m1380", r"5\%")]
OK = ("phi_ub", "ub_target", "ub_rel", "certified", "gap_rel", "gap_abs", "converged")


def key_of(n, cat, k):
    return "n%d_%s" % (n, cat) if k == 0 else "n%d_%s_lam%d" % (n, cat, k)


def load(candidates):
    for name in candidates:
        p = find(name, first=[OUT])
        if p:
            return json.load(open(p))
    return None


def pairwise_rec(n, k):
    key = key_of(n, "sparse", k)
    return load(["race_cgbfqp_%s.json" % key, "race_cgbfqp-stream_u24_%s.json" % key,
                 "race_cgbfqp-stream_f32_%s.json" % key, "race_cgbfqp-stream_u16_%s.json" % key])


def density_rec(cat, k):
    key = key_of(20, cat, k)
    return load(["race_bm_admm_%s.json" % key, "bm_admm_race_%s.json" % key])


def grid_rec(n, cat, k, solver):
    key = key_of(n, cat, k)
    return load(["%s_race_%s.json" % (solver, key), "race_%s_%s.json" % (solver, key)])


def status(r):
    if r is None:
        return None
    if r.get("stop") == "infeasible":
        return "infeasible"
    if r.get("wall_s") is None or r.get("stop") in ("error", "killed"):
        return "err"
    if r.get("stop") in OK or r.get("converged"):
        return "ok"
    return "cap"


def t(x):
    return ("%.2f" % x) if x < 10 else ("%.1f" % x)


def cell(r, count=None):
    st = status(r)
    if st is None:
        return ""
    if st in ("infeasible", "err"):
        # '--' = no measurement: either refused before the clock started (device memory)
        # or the run failed while executing. The record keeps which (stop=infeasible/error).
        return "--"
    if st == "cap":
        return "CAP"
    s = t(r["wall_s"])
    if count and r.get("iters") is not None:
        s += " (%s %s)" % (format(int(r["iters"]), ","), count)
    return s


def num(x):
    return format(int(x), ",").replace(",", "{,}")


def crit(k):
    return "$(\\mathrm{UB}-\\mathrm{OPT})/\\mathrm{OPT} \\le 1\\%$" if k < 10 else "$\\mathrm{UB} \\le 10^{-3}$ (the point is inside the polytope, $\\mathrm{OPT}=0$)"


def write(name, lines):
    os.makedirs(TABLES, exist_ok=True)
    p = os.path.join(TABLES, name + ".tex")
    open(p, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    return p


def main():
    md = ["# Lambda study: every number (time in s; counts in parentheses)\n",
          "Stopping rule UB <= max(1.01 OPT, 1e-3). p(lambda) = lambda p_inside + (1 - lambda) p_hat.\n"]
    written = []
    # ---- pairwise
    for k, suf, lam in LAMS:
        L = ["% generated by validation/make_lambda_tables.py", "\\begin{table}[t]", "\\centering",
             "\\caption{Feasibility in the number of alternatives, pairwise design ($m_p = n(n-1)$), $\\lambda = %s$: "
             "time to %s in seconds (columns generated).}" % (lam, crit(k)),
             "\\label{tab:fes_pairwise_%s}" % suf, "\\begin{tabular}{rrrrr}", "\\toprule",
             "$n$ & $m_p$ & CGBFQP-GPU & CGIP & CGIP-heur \\\\", "\\midrule"]
        md += ["\n## pairwise, lambda = %s\n" % lam, "| n | m_p | OPT | CGBFQP-GPU | backend |", "|---|---|---|---|---|"]
        for n in PAIRWISE_N:
            r = pairwise_rec(n, k)
            ref = REFS.get(key_of(n, "sparse", k), {})
            mark = "$^{\\ddagger}$" if (r and r.get("pricing", "mask") != "mask") else ""
            L.append("%d & %s & %s%s &  &  \\\\" % (n, num(n * (n - 1)), cell(r, "cols"), mark))
            md.append("| %d | %d | %s | %s | %s |" % (n, n * (n - 1), ("%.6f" % ref["opt"]) if ref else "-", cell(r, "cols"), (r or {}).get("pricing", "mask") if r else "-"))
        L += ["\\bottomrule", "\\end{tabular}", "\\end{table}",
              "\\smallskip\\par\\footnotesize $^{\\ddagger}$ two-layer uint24 block-scaled pricing backend (the mask-indexed lattice does not fit for $n \\ge 33$)."]
        written.append(write("tab_fes_pairwise_" + suf, L))
    # ---- density
    for k, suf, lam in LAMS:
        L = ["% generated by validation/make_lambda_tables.py", "\\begin{table}[t]", "\\centering",
             "\\caption{Feasibility in observation density, $n = 20$ ($m_2 = 10{,}485{,}760$), $\\lambda = %s$: "
             "BM-ADMM time to %s in seconds (ADMM iterations).}" % (lam, crit(k)),
             "\\label{tab:fes_density_%s}" % suf, "\\begin{tabular}{lrrrr}", "\\toprule",
             "density & $m_p$ & BM-ADMM & CGIP & CGIP-heur \\\\", "\\midrule"]
        md += ["\n## density n = 20, lambda = %s\n" % lam, "| density | m_p | OPT | BM-ADMM |", "|---|---|---|---|"]
        for cat, label in DENSITY:
            r = density_rec(cat, k)
            ref = REFS.get(key_of(20, cat, k), {})
            mp = ref.get("mp") or (r or {}).get("mp") or 0
            L.append("%s & %s & %s &  &  \\\\" % (label, num(mp), cell(r, "it")))
            md.append("| %s | %d | %s | %s |" % (label.replace("\\", ""), mp, ("%.6f" % ref["opt"]) if ref else "-", cell(r, "it")))
        L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
        written.append(write("tab_fes_density_" + suf, L))
    # ---- grid races
    manifest = json.load(open(os.path.join(ROOT, "data", "manifest.json")))
    for n in (18, 19, 20):
        for k, suf, lam in LAMS:
            L = ["% generated by validation/make_lambda_tables.py", "\\begin{table}[t]", "\\centering",
                 "\\caption{$n=%d$ ($m_2 = %s$), $\\lambda = %s$: time to %s in seconds; bold = fastest of the GPU solvers. "
                 "``--'' = no measurement: the solver cannot run the cell (device memory) or the run failed; CAP = wall cap.}" % (n, num(n * (1 << (n - 1))), lam, crit(k)),
                 "\\label{tab:race_n%d_%s}" % (n, suf), "\\begin{tabular}{lrrrrrr}", "\\toprule",
                 "density & $m_p$ & BM-ADMM & CGBFQP-GPU & Flow-ADMM & CGIP & CGIP-heur \\\\", "\\midrule"]
            md += ["\n## n = %d, lambda = %s\n" % (n, lam), "| density | m_p | OPT | BM-ADMM | CGBFQP-GPU | Flow-ADMM |", "|---|---|---|---|---|---|"]
            for cat in CELLS[n]:
                m = manifest["n%d_%s" % (n, cat)]
                dens = "pairwise" if cat == "sparse" else ("%.3f\\%%" % m["density_pct"] if m["density_pct"] < 1 else "%.2f\\%%" % m["density_pct"])
                recs = {s: grid_rec(n, cat, k, s) for s in ("bm_admm", "cgbfqp", "flow_admm")}
                ok = {s: r["wall_s"] for s, r in recs.items() if status(r) == "ok"}
                best = min(ok, key=ok.get) if ok else None
                cells = []
                for s in ("bm_admm", "cgbfqp", "flow_admm"):
                    c = cell(recs[s])
                    cells.append(("\\textbf{%s}" % c) if s == best else c)
                L.append("%s & %s & %s &  &  \\\\" % (dens, num(m["mp"]), " & ".join(cells)))
                ref = REFS.get(key_of(n, cat, k), {})
                md.append("| %s | %d | %s | %s | %s | %s |" % (dens.replace("\\", ""), m["mp"], ("%.6f" % ref["opt"]) if ref else "-",
                          cell(recs["bm_admm"], "it"), cell(recs["cgbfqp"], "cols"), cell(recs["flow_admm"], "it")))
            L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
            written.append(write("tab_race_n%d_%s" % (n, suf), L))
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, "LAMBDA_STUDY.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
    print("wrote %d tables under paper/tables and %s" % (len(written), os.path.join(OUT, "LAMBDA_STUDY.md")))


if __name__ == "__main__":
    main()
